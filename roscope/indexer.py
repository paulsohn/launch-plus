def _read_package_deps(
    lockfile: Lockfile,
    src_dir: Path,
    pkg_name: str,
) -> Dependencies | None:
    """Read on-disk package.xml dependencies for a package."""
    pkg_lock = lockfile.packages.get(pkg_name)
    if pkg_lock is None:
        return None
    xml_path = src_dir / pkg_lock.repo / pkg_lock.path / "package.xml"
    try:
        content = xml_path.read_text()
    except OSError:
        return None
    try:
        info = parse_package_xml(content, str(xml_path))
        return info.dependencies
    except RoscopeError:
        return None


def resolve_dependencies(
    lockfile: Lockfile,
    src_dir: Path,
    root_packages: set[str],
    mode: DependencyMode,
) -> DependencyGraph:
    """Compute transitive dependencies for a set of root packages.

    Reads dependency information from on-disk ``package.xml`` files.
    Packages not on disk are treated as leaves.
    """
    result = DependencyGraph()
    queue = list(root_packages)
    visited: set[str] = set()

    while queue:
        pkg_name = queue.pop()
        if pkg_name in visited:
            continue
        visited.add(pkg_name)

        if pkg_name not in lockfile.packages:
            result.external.add(pkg_name)
            continue

        result.packages.add(pkg_name)

        deps = _read_package_deps(lockfile, src_dir, pkg_name)
        if deps is None:
            result.missing.add(pkg_name)
            continue

        if mode == DependencyMode.BUILD:
            queue.extend(deps.build)
            queue.extend(deps.build_export)
            queue.extend(deps.buildtool)
            queue.extend(deps.buildtool_export)
        elif mode == DependencyMode.EXEC:
            queue.extend(deps.exec)
        elif mode == DependencyMode.BUILD_AND_EXEC:
            queue.extend(deps.build)
            queue.extend(deps.build_export)
            queue.extend(deps.buildtool)
            queue.extend(deps.buildtool_export)
            queue.extend(deps.exec)
        elif mode == DependencyMode.ALL:
            queue.extend(deps.build)
            queue.extend(deps.build_export)
            queue.extend(deps.buildtool)
            queue.extend(deps.buildtool_export)
            queue.extend(deps.exec)
            queue.extend(deps.test)

    return result


def compute_build_order(
    lockfile: Lockfile,
    src_dir: Path,
    packages: set[str],
) -> list[str]:
    """Compute build order for packages using topological sort (Kahn's algorithm).

    Returns packages in dependency order (dependencies first).
    """
    in_degree: dict[str, int] = dict.fromkeys(packages, 0)
    dependents: dict[str, list[str]] = defaultdict(list)

    for pkg in packages:
        deps = _read_package_deps(lockfile, src_dir, pkg)
        if deps is None:
            continue
        build_deps = deps.build + deps.build_export + deps.buildtool + deps.buildtool_export
        for dep in build_deps:
            if dep in packages:
                in_degree[pkg] += 1
                dependents[dep].append(pkg)

    # Kahn's algorithm
    result: list[str] = []
    queue = sorted(pkg for pkg, deg in in_degree.items() if deg == 0)

    while queue:
        pkg = queue.pop()
        result.append(pkg)

        for dep in dependents.get(pkg, []):
            in_degree[dep] -= 1
            if in_degree[dep] == 0:
                queue.append(dep)
                queue.sort()

    # Add any remaining packages (cycles) at the end
    for pkg in sorted(packages):
        if pkg not in result:
            result.append(pkg)

    return result
