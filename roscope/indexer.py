def _run_git(
    args: list[str],
    *,
    cwd: Path | str | None = None,
    check: bool = True,
) -> subprocess.CompletedProcess[str]:
    """Run a git command and return the result."""
    try:
        result = subprocess.run(
            ["git", *args],
            cwd=cwd,
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError as e:
        raise GitError(f"failed to run git {args[0]}: {e}") from e

    if check and result.returncode != 0:
        raise GitError(f"git {' '.join(args)} failed: {result.stderr.strip()}")

    return result


def _run_git_bytes(
    args: list[str],
    *,
    cwd: Path | str | None = None,
    check: bool = True,
) -> subprocess.CompletedProcess[bytes]:
    """Run a git command returning raw bytes (for binary output like ``git archive``)."""
    try:
        result = subprocess.run(
            ["git", *args],
            cwd=cwd,
            capture_output=True,
            check=False,
        )
    except OSError as e:
        raise GitError(f"failed to run git {args[0]}: {e}") from e

    if check and result.returncode != 0:
        raise GitError(
            f"git {' '.join(args)} failed: {result.stderr.decode(errors='replace').strip()}"
        )

    return result


def resolve_version_local(repo_dir: Path, url: str, version_ref: str) -> str:
    """Resolve a ref to a SHA using a local clone via ``git fetch``.

    Preferred over ls-remote when a local clone exists.
    """
    _run_git(["fetch", "--", url, version_ref], cwd=repo_dir)
    result = _run_git(["rev-parse", "FETCH_HEAD"], cwd=repo_dir)
    sha = result.stdout.strip()
    logger.debug("Resolved %s to SHA %s via local fetch", version_ref, sha)
    return sha


def blobless_clone(url: str, repo_dir: Path) -> None:
    """Blobless no-checkout clone of a repository."""
    if repo_dir.parent and not repo_dir.parent.exists():
        repo_dir.parent.mkdir(parents=True, exist_ok=True)
    logger.debug("Blobless clone %s into %s", url, repo_dir)
    _run_git(["clone", "--filter=blob:none", "--no-checkout", url, str(repo_dir)])


def ensure_remote_url(repo_dir: Path, expected_url: str) -> None:
    """Ensure origin URL matches for partial clones.

    Blobless/partial clones use origin as the promisor remote. If the manifest
    URL changed, origin must be updated.
    """
    # Only act on partial clones
    result = _run_git(
        ["config", "--get", "remote.origin.partialclonefilter"],
        cwd=repo_dir,
        check=False,
    )
    if result.returncode != 0:
        return  # Not a partial clone

    result = _run_git(["remote", "get-url", "origin"], cwd=repo_dir, check=False)
    if result.returncode != 0:
        return  # No origin remote
    current_url = result.stdout.strip()

    if current_url == expected_url:
        return

    logger.debug("Updating origin URL for %s to %s", repo_dir, expected_url)
    _run_git(["remote", "set-url", "origin", expected_url], cwd=repo_dir)


# ---------------------------------------------------------------------------
# Package discovery
# ---------------------------------------------------------------------------


def discover_packages(
    url: str,
    sha: str,
    repo_dir: Path | None = None,
    recurse_submodules: bool = False,
) -> list[PackageInfo]:
    """Discover all packages in a repository and parse their package.xml files.

    Three strategies are tried in order:
    1. Existing local repo: inspect objects via ``git ls-tree`` + ``git show``
    2. ``git archive --remote``: fetch tree as tar stream
    3. Blobless clone into repo_dir, then strategy 1
    """
    # Strategy 1: existing local repo
    if repo_dir is not None and repo_dir.exists() and (repo_dir / ".git").exists():
        logger.debug("Using existing repo at %s", repo_dir)
        return _discover_from_existing_repo(repo_dir, url, sha, recurse_submodules)

    # Strategy 2: git archive (skip if submodules needed)
    if not recurse_submodules:
        result = _run_git_bytes(["archive", "--remote", url, sha], check=False)
        if result.returncode == 0:
            return _discover_from_tar(result.stdout)

    # Strategy 3: blobless clone
    if repo_dir is None:
        raise GitError("a source directory (--src) is required to clone repositories")

    blobless_clone(url, repo_dir)
    return _discover_from_existing_repo(repo_dir, url, sha, recurse_submodules)


def _discover_from_tar(tar_data: bytes) -> list[PackageInfo]:
    """Discover packages from a tar archive (git archive output)."""
    packages: list[PackageInfo] = []
    with tarfile.open(fileobj=io.BytesIO(tar_data)) as archive:
        for member in archive.getmembers():
            path_str = member.name
            if not (path_str.endswith("/package.xml") or path_str == "package.xml"):
                continue
            f = archive.extractfile(member)
            if f is None:
                continue
            content = f.read().decode("utf-8", errors="replace")
            parent = str(Path(path_str).parent)
            pkg_path = parent if parent != "." else "."

            try:
                info = parse_package_xml(content, pkg_path)
                logger.debug("Found package '%s' at %s", info.name, pkg_path)
                packages.append(info)
            except RoscopeError as e:
                logger.warning("Failed to parse %s: %s", path_str, e)

    logger.debug("Found %d packages from archive", len(packages))
    return packages


def _discover_from_existing_repo(
    repo_dir: Path,
    url: str,
    sha: str,
    recurse_submodules: bool,
) -> list[PackageInfo]:
    """Discover packages from an existing git repository using git object inspection."""
    # Fetch the SHA directly from the URL
    logger.debug("Fetching %s from %s in existing repo...", sha, url)
    result = _run_git(["fetch", "--depth=1", "--", url, sha], cwd=repo_dir, check=False)
    if result.returncode != 0:
        logger.debug("Specific SHA fetch failed, trying general fetch...")
        _run_git(["fetch", "--depth=1", "--", url], cwd=repo_dir, check=False)

    packages = _discover_from_git_objects(repo_dir, sha)

    if recurse_submodules:
        sub_packages = _discover_from_submodules(repo_dir, sha)
        packages.extend(sub_packages)

    logger.debug("Found %d packages via git object inspection", len(packages))
    return packages


def _discover_from_git_objects(repo_dir: Path, sha: str) -> list[PackageInfo]:
    """Discover packages by reading git objects directly (no checkout needed)."""
    result = _run_git(["ls-tree", "-r", "--name-only", sha], cwd=repo_dir)
    packages: list[PackageInfo] = []

    for line in result.stdout.splitlines():
        if not (line.endswith("/package.xml") or line == "package.xml"):
            continue

        file_ref = f"{sha}:{line}"
        content_result = _run_git(["show", file_ref], cwd=repo_dir, check=False)
        if content_result.returncode != 0:
            continue

        parent = str(Path(line).parent)
        pkg_path = parent if parent != "." else "."

        try:
            info = parse_package_xml(content_result.stdout, pkg_path)
            logger.debug("Found package '%s' at %s", info.name, pkg_path)
            packages.append(info)
        except RoscopeError as e:
            logger.warning("Failed to parse %s: %s", line, e)

    return packages


def _discover_from_submodules(repo_dir: Path, sha: str) -> list[PackageInfo]:
    """Discover packages from submodules using git object inspection."""
    gitmodules_ref = f"{sha}:.gitmodules"
    result = _run_git(["show", gitmodules_ref], cwd=repo_dir, check=False)
    if result.returncode != 0:
        return []

    packages: list[PackageInfo] = []
    current_path: str | None = None

    for line in result.stdout.splitlines():
        trimmed = line.strip()
        if trimmed.startswith("path = "):
            current_path = trimmed[len("path = ") :]
        elif trimmed.startswith("[submodule"):
            current_path = None

        if current_path is None:
            continue

        path = current_path
        # Get submodule commit SHA from the tree
        ls_result = _run_git(["ls-tree", sha, path], cwd=repo_dir, check=False)
        if ls_result.returncode != 0:
            current_path = None
            continue

        first_line = ls_result.stdout.splitlines()[0] if ls_result.stdout.strip() else ""
        parts = first_line.split()
        if len(parts) >= 3 and parts[1] == "commit":
            submodule_sha = parts[2]
            submodule_dir = repo_dir / path

            if (submodule_dir / ".git").exists():
                logger.debug(
                    "Inspecting submodule at %s (SHA: %s)",
                    path,
                    submodule_sha[:8],
                )
                _run_git(
                    ["fetch", "--depth=1", "origin", submodule_sha],
                    cwd=submodule_dir,
                    check=False,
                )
                try:
                    sub_packages = _discover_from_git_objects(submodule_dir, submodule_sha)
                    for pkg in sub_packages:
                        pkg.path = f"{path}/{pkg.path}"
                    packages.extend(sub_packages)
                except RoscopeError:
                    pass

        current_path = None

    return packages


# ---------------------------------------------------------------------------
# Version resolution
# ---------------------------------------------------------------------------


def _resolve_version_from_repo(
    url: str,
    version: str,
    repo_dir: Path | None,
) -> str:
    """Resolve a version (tag, branch, or SHA) to a concrete SHA."""
    # Short-circuit: full SHAs are already resolved
    if len(version) == 40 and all(c in "0123456789abcdefABCDEF" for c in version):
        logger.debug("Version %s is a full SHA, using directly", version)
        return version

    if repo_dir is None:
        raise GitError(
            f"a source directory (--src) is required to resolve non-SHA version '{version}'"
        )

    # Ensure a local clone exists
    if not (repo_dir / ".git").exists():
        blobless_clone(url, repo_dir)
    else:
        ensure_remote_url(repo_dir, url)

    return resolve_version_local(repo_dir, url, version)


# ---------------------------------------------------------------------------
# Lockfile generation
# ---------------------------------------------------------------------------


def generate_lockfile(
    repos: ReposFile,
    src_dir: Path | None = None,
    recurse_submodules: bool = False,
) -> Lockfile:
    """Generate a lockfile from a .repos file.

    Resolves versions to SHAs and discovers packages in each repository.
    """
    lockfile = Lockfile()

    for workspace_path, entry in repos.repositories.items():
        if entry.repo_type != "git":
            logger.warning(
                "Skipping non-git repository at %s: type=%s",
                workspace_path,
                entry.repo_type,
            )
            continue

        repo_dir = src_dir / workspace_path if src_dir is not None else None

        # Resolve version to SHA
        sha = _resolve_version_from_repo(entry.url, entry.version, repo_dir)
        logger.debug("Resolved %s %s -> %s", workspace_path, entry.version, sha)

        # Discover packages
        packages = discover_packages(entry.url, sha, repo_dir, recurse_submodules)

        package_names = sorted(p.name for p in packages)

        # Only include ref if different from resolved SHA
        version_ref = entry.version if entry.version != sha else None

        lockfile.repositories[workspace_path] = RepoLock(
            url=entry.url,
            version=sha,
            repo_type="git",
            version_ref=version_ref,
            packages=package_names,
        )

        for pkg in packages:
            if pkg.name in lockfile.packages:
                existing = lockfile.packages[pkg.name]
                raise RoscopeError(
                    f"duplicate package '{pkg.name}' found in repos "
                    f"'{existing.repo}' and '{workspace_path}'"
                )
            lockfile.packages[pkg.name] = PackageLock(
                repo=workspace_path,
                path=pkg.path,
            )

    return lockfile


# ---------------------------------------------------------------------------
# Source directory scanning (dirty mode)
# ---------------------------------------------------------------------------


def scan_source_dir(src_dir: Path) -> Lockfile:
    """Build a synthetic Lockfile by scanning a source directory for packages.

    Walks ``src_dir`` recursively, finds every ``package.xml``, and maps each
    package to a ``PackageLock``.  The resulting ``Lockfile`` has empty
    ``url`` / ``version`` fields (sufficient for dirty-mode resolution, where
    git operations are never performed).

    Intended for ``--dirty`` mode: lets users work without a lockfile after
    a plain ``vcs import src < some.repos``.  Works equally well when there is
    no remote, or when the directory is not a git repository at all.

    Traversal rules:
    - Recurse into every subdirectory except ``.git/``.
    - When ``package.xml`` is found at a node, record the package and stop
      recursing into that directory (ROS packages don't nest inside each other).
    - Duplicate package names: warn and keep the first occurrence.
    """
    lockfile = Lockfile()
    seen: dict[str, Path] = {}  # pkg_name -> first absolute path
    src_dir = src_dir.resolve()

    def _walk(directory: Path) -> None:
        try:
            entries = sorted(directory.iterdir())
        except OSError:
            return
        for entry in entries:
            if not entry.is_dir() or entry.name == ".git":
                continue
            xml = entry / "package.xml"
            if xml.exists():
                try:
                    info = parse_package_xml(xml.read_text(), str(xml))
                except RoscopeError as e:
                    logger.warning("scan_source_dir: skipping %s: %s", xml, e)
                    continue

                if info.name in seen:
                    logger.warning(
                        "scan_source_dir: duplicate package '%s' at %s and %s; keeping first",
                        info.name,
                        seen[info.name],
                        entry,
                    )
                    continue

                seen[info.name] = entry

                # repo  = immediate child of src_dir that contains this package
                # path  = relative path from that child to the package dir
                # fetch_dir / repo / path  must equal entry.resolve()
                try:
                    rel = entry.relative_to(src_dir)
                except ValueError:
                    logger.warning("scan_source_dir: %s outside src_dir; skipping", entry)
                    continue
                repo_key = rel.parts[0]  # immediate child of src_dir
                path_in_repo = str(Path(*rel.parts[1:])) if len(rel.parts) > 1 else "."

                if repo_key not in lockfile.repositories:
                    lockfile.repositories[repo_key] = RepoLock(url="", version="")

                lockfile.packages[info.name] = PackageLock(
                    repo=repo_key,
                    path=path_in_repo,
                )
                # Do not recurse: ROS packages don't contain other packages
            else:
                _walk(entry)

    _walk(src_dir)
    logger.info(
        "scan_source_dir: found %d packages in %d repos under %s",
        len(lockfile.packages),
        len(lockfile.repositories),
        src_dir,
    )
    return lockfile


