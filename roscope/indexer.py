# package.xml parsing
# ---------------------------------------------------------------------------

_DEP_TAG_MAP = {
    "build_depend": "build",
    "build_export_depend": "build_export",
    "buildtool_depend": "buildtool",
    "buildtool_export_depend": "buildtool_export",
    "exec_depend": "exec",
    "test_depend": "test",
}


def parse_package_xml(content: str, path: str) -> PackageInfo:
    """Parse package.xml content to extract package information."""
    try:
        root = ET.fromstring(content)  # noqa: S314
    except ET.ParseError as e:
        raise XmlParseError(f"failed to parse package.xml at {path}: {e}") from e

    name_el = root.find("name")
    if name_el is None or not (name_el.text or "").strip():
        raise XmlParseError("package.xml missing <name> element")

    name = (name_el.text or "").strip()
    deps = Dependencies()

    for tag, attr in _DEP_TAG_MAP.items():
        dep_list: list[str] = getattr(deps, attr)
        for el in root.findall(tag):
            cond = el.get("condition")
            if cond is not None:
                try:
                    if not evaluate_condition(cond):
                        continue
                except ValueError:
                    logger.warning("failed to evaluate condition '%s'; including dependency", cond)
            dep_text = (el.text or "").strip()
            if dep_text and dep_text not in dep_list:
                dep_list.append(dep_text)

    # <depend> expands to build + build_export + exec (REP-149 §3)
    for el in root.findall("depend"):
        cond = el.get("condition")
        if cond is not None:
            try:
                if not evaluate_condition(cond):
                    continue
            except ValueError:
                logger.warning("failed to evaluate condition '%s'; including dependency", cond)
        dep_text = (el.text or "").strip()
        if dep_text:
            if dep_text not in deps.build:
                deps.build.append(dep_text)
            if dep_text not in deps.build_export:
                deps.build_export.append(dep_text)
            if dep_text not in deps.exec:
                deps.exec.append(dep_text)

    # Sort all lists for deterministic output
    deps.build.sort()
    deps.build_export.sort()
    deps.buildtool.sort()
    deps.buildtool_export.sort()
    deps.exec.sort()
    deps.test.sort()

    return PackageInfo(name=name, path=path, dependencies=deps)


