"""Indexer module: parse .repos files and generate lockfiles.

The indexer is responsible for:
- Parsing .repos YAML files (VCS format)
- Resolving versions (tags/branches/SHAs) to concrete SHAs via blobless clone
- Fetching package.xml files from git objects (no working tree needed)
- Generating dual-indexed lockfiles (repos + packages)
"""

from __future__ import annotations

import io
import logging
import os
import subprocess
import tarfile
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

import yaml

from roscope.exceptions import GitError, RoscopeError, XmlParseError
from roscope.types import (
    Dependencies,
    DependencyGraph,
    DependencyMode,
    Lockfile,
    PackageInfo,
    PackageLock,
    RepoEntry,
    RepoLock,
    ReposFile,
)

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# YAML parsing / serialization
# ---------------------------------------------------------------------------

LOCKFILE_HEADER = """\
# roscope lockfile (VCS-compatible)
#
# This file is auto-generated by `roscope index`. Do not edit manually.
# To regenerate, run: roscope index <your.repos>
#
# VCS import: vcs import src < manifest.lock.repos
#
# This lockfile pins exact commit SHAs for all repositories in your .repos file,
# ensuring reproducible builds. It contains:
#   - repositories: Repository metadata with pinned SHAs (VCS-compatible)
#   - packages: Package index for O(1) dependency lookup
#
"""


def parse_repos(content: str) -> ReposFile:
    """Parse a .repos file from YAML content."""
    raw = yaml.safe_load(content)
    if not isinstance(raw, dict) or "repositories" not in raw:
        raise RoscopeError("invalid .repos file: missing 'repositories' key")

    repos: dict[str, RepoEntry] = {}
    for path, entry in raw["repositories"].items():
        repos[path] = RepoEntry(
            repo_type=entry.get("type", "git"),
            url=entry["url"],
            version=entry["version"],
        )
    return ReposFile(repositories=repos)


def parse_lockfile(content: str) -> Lockfile:
    """Parse a lockfile from YAML content."""
    raw = yaml.safe_load(content)
    if not isinstance(raw, dict):
        raise RoscopeError("invalid lockfile: not a YAML mapping")

    lockfile = Lockfile()

    for ws_path, repo_raw in (raw.get("repositories") or {}).items():
        lockfile.repositories[ws_path] = RepoLock(
            url=repo_raw["url"],
            version=repo_raw["version"],
            repo_type=repo_raw.get("type", "git"),
            version_ref=repo_raw.get("ref"),
            packages=list(repo_raw.get("packages", [])),
        )

    for pkg_name, pkg_raw in (raw.get("packages") or {}).items():
        lockfile.packages[pkg_name] = PackageLock(
            repo=pkg_raw["repo"],
            path=pkg_raw["path"],
        )

    return lockfile


def serialize_lockfile(lockfile: Lockfile) -> str:
    """Serialize a lockfile to YAML with header comment."""
    # Build ordered dict for deterministic output
    repos_out: dict[str, dict] = {}
    for ws_path in sorted(lockfile.repositories):
        repo = lockfile.repositories[ws_path]
        entry: dict = {
            "type": repo.repo_type,
            "url": repo.url,
            "version": repo.version,
        }
        if repo.version_ref is not None:
            entry["ref"] = repo.version_ref
        entry["packages"] = sorted(repo.packages)
        repos_out[ws_path] = entry

    pkgs_out: dict[str, dict] = {}
    for pkg_name in sorted(lockfile.packages):
        pkg = lockfile.packages[pkg_name]
        pkgs_out[pkg_name] = {"repo": pkg.repo, "path": pkg.path}

    data = {"repositories": repos_out, "packages": pkgs_out}
    body: str = yaml.dump(data, default_flow_style=False, sort_keys=False)
    return LOCKFILE_HEADER + body


# ---------------------------------------------------------------------------
# REP-149 condition expression evaluator
# ---------------------------------------------------------------------------


def evaluate_condition(condition: str) -> bool:
    """Evaluate a REP-149 condition expression against the current environment.

    Returns True if the condition evaluates to true (or is empty).

    Implements the full REP-149 condition grammar:
    - Comparison operators: ==, !=, <, <=, >, >= (string comparison)
    - Logical operators: and, or (left-associative, ``and`` binds tighter)
    - Parentheses for grouping
    - Terms: $VAR (env variable), bare words (alphanums/_/-), quoted strings
    """
    return _evaluate_condition_impl(condition, os.environ.get)


def _evaluate_condition_impl(
    condition: str,
    env_lookup: object,
) -> bool:
    """Evaluate with an injectable env lookup (for testing)."""
    tokens = _tokenize_condition(condition)
    if not tokens:
        return True
    parser = _ConditionParser(tokens, env_lookup)  # type: ignore[arg-type]
    result = parser.parse_expr()
    if parser.pos != len(parser.tokens):
        raise ValueError(f"unexpected token at position {parser.pos}: {parser.tokens[parser.pos]}")
    return result


def _tokenize_condition(s: str) -> list[tuple[str, str]]:
    """Tokenize a condition string into (type, value) tuples."""
    tokens: list[tuple[str, str]] = []
    chars = list(s)
    i = 0
    n = len(chars)

    while i < n:
        c = chars[i]

        if c.isspace():
            i += 1
            continue

        if c == "(":
            tokens.append(("LPAREN", "("))
            i += 1
            continue

        if c == ")":
            tokens.append(("RPAREN", ")"))
            i += 1
            continue

        # Two-char comparison operators
        if i + 1 < n:
            two = chars[i] + chars[i + 1]
            if two in ("==", "!=", "<=", ">="):
                tokens.append(("CMP", two))
                i += 2
                continue

        if c == "<":
            tokens.append(("CMP", "<"))
            i += 1
            continue
        if c == ">":
            tokens.append(("CMP", ">"))
            i += 1
            continue

        # Variable: $[A-Za-z0-9_]+
        if c == "$":
            start = i + 1
            i += 1
            while i < n and (chars[i].isalnum() or chars[i] == "_"):
                i += 1
            if i == start:
                raise ValueError("empty variable name after '$'")
            tokens.append(("VAR", "".join(chars[start:i])))
            continue

        # Quoted string
        if c in ('"', "'"):
            quote = c
            i += 1
            start = i
            while i < n and chars[i] != quote:
                i += 1
            if i >= n:
                raise ValueError(f"unterminated {quote}-quoted string")
            tokens.append(("LIT", "".join(chars[start:i])))
            i += 1  # skip closing quote
            continue

        # Bare word: alphanums, underscore, dash
        if c.isalnum() or c in ("_", "-"):
            start = i
            while i < n and (chars[i].isalnum() or chars[i] in ("_", "-")):
                i += 1
            word = "".join(chars[start:i])
            if word == "and":
                tokens.append(("AND", "and"))
            elif word == "or":
                tokens.append(("OR", "or"))
            else:
                tokens.append(("LIT", word))
            continue

        raise ValueError(f"unexpected character '{c}'")

    return tokens


class _ConditionParser:
    """Recursive-descent parser/evaluator for REP-149 conditions."""

    def __init__(
        self,
        tokens: list[tuple[str, str]],
        env_lookup: object,
    ) -> None:
        self.tokens = tokens
        self.pos = 0
        self._env_lookup = env_lookup

    def _resolve(self, tok: tuple[str, str]) -> str:
        kind, val = tok
        if kind == "VAR":
            result = self._env_lookup(val)  # type: ignore[operator]
            return result if result is not None else ""
        if kind == "LIT":
            return val
        raise ValueError(f"expected term, got {tok}")

    def _peek(self) -> tuple[str, str] | None:
        return self.tokens[self.pos] if self.pos < len(self.tokens) else None

    def _next(self) -> tuple[str, str] | None:
        if self.pos < len(self.tokens):
            tok = self.tokens[self.pos]
            self.pos += 1
            return tok
        return None

    def parse_expr(self) -> bool:
        return self._parse_or()

    def _parse_or(self) -> bool:
        result = self._parse_and()
        while self._peek() == ("OR", "or"):
            self._next()
            rhs = self._parse_and()
            result = result or rhs
        return result

    def _parse_and(self) -> bool:
        result = self._parse_atom()
        while self._peek() == ("AND", "and"):
            self._next()
            rhs = self._parse_atom()
            result = result and rhs
        return result

    def _parse_atom(self) -> bool:
        if self._peek() == ("LPAREN", "("):
            self._next()
            result = self.parse_expr()
            if self._next() != ("RPAREN", ")"):
                raise ValueError("expected ')'")
            return result
        return self._parse_comparison()

    def _parse_comparison(self) -> bool:
        lhs_tok = self._next()
        if lhs_tok is None:
            raise ValueError("expected term")
        lhs = self._resolve(lhs_tok)

        op_tok = self._next()
        if op_tok is None or op_tok[0] != "CMP":
            raise ValueError(f"expected comparison operator, got {op_tok}")
        op = op_tok[1]

        rhs_tok = self._next()
        if rhs_tok is None:
            raise ValueError("expected term after operator")
        rhs = self._resolve(rhs_tok)

        if op == "==":
            return lhs == rhs
        if op == "!=":
            return lhs != rhs
        if op == "<":
            return lhs < rhs
        if op == "<=":
            return lhs <= rhs
        if op == ">":
            return lhs > rhs
        if op == ">=":
            return lhs >= rhs
        raise ValueError(f"unknown operator: {op}")


